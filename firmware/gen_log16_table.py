#!/usr/bin/env python3
"""Write (or --check) firmware/iwr6843/two_round_log16.h, the overview's log16 thresholds.

The overview codes a power p >= 1 as round(5000 * log10(p)) (two_round.py
``log16_encode``). The code steps from c to c + 1 where 5000 * log10(p) = c + 1/2,
i.e. at t_c = 10 ** ((2c + 1) / 10000), irrational for every c, so no double is
ever exactly on a step. One decade of thresholds (c = 0..4999, t_c in [1, 10))
codes every power: code = 5000 * k + #{c : t_c < p / 10**k} for 10**k <= p < 10**(k+1).

Each t_c is stored as two doubles (hi = t_c rounded to nearest, lo = the rest
rounded to nearest), as IEEE-754 bit patterns, computed here with 60-digit decimal
arithmetic straight from the definition.

    python firmware/gen_log16_table.py           # rewrite the header
    python firmware/gen_log16_table.py --check   # exit 1 if it is stale
"""

from __future__ import annotations

import decimal
import struct
import sys
from pathlib import Path

HEADER = Path(__file__).resolve().parent / "iwr6843" / "two_round_log16.h"
CODES_PER_DECADE = 5000
PRECISION = 60


def thresholds() -> list[decimal.Decimal]:
    """t_c = 10 ** ((2c + 1) / 10000) for c = 0..4999, to PRECISION digits."""
    context = decimal.Context(prec=PRECISION)
    ln10 = context.ln(decimal.Decimal(10))
    return [
        context.exp(context.multiply(ln10, decimal.Decimal(2 * c + 1) / (2 * CODES_PER_DECADE)))
        for c in range(CODES_PER_DECADE)
    ]


def _bits(value: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", value))[0]


def render() -> str:
    his, los = [], []
    with decimal.localcontext(decimal.Context(prec=PRECISION)):
        for t in thresholds():
            hi = float(t)  # str -> double: correctly rounded
            lo = float(t - decimal.Decimal(hi))
            his.append(_bits(hi))
            los.append(_bits(lo))

    def table(name: str, values: list[int]) -> list[str]:
        out = [f"static const uint64_t {name}[L3TR_LOG16_THRESHOLDS] = {{"]
        for at in range(0, len(values), 4):
            out.append("    " + " ".join(f"0x{v:016X}ULL," for v in values[at : at + 4]))
        out.append("};")
        return out

    lines = [
        "/* Generated by firmware/gen_log16_table.py; do not edit. */",
        "#ifndef OPENFLIGHT_TWO_ROUND_LOG16_H",
        "#define OPENFLIGHT_TWO_ROUND_LOG16_H",
        "",
        "#include <stdint.h>",
        "",
        "/* t_c = 10^((2c+1)/10000), c = 0..4999: the log16 code steps from c to c+1 at",
        " * p = t_c (one decade). hi = t_c rounded to the nearest double, lo = t_c - hi",
        " * rounded to the nearest double; both as IEEE-754 binary64 bit patterns. */",
        f"#define L3TR_LOG16_THRESHOLDS {CODES_PER_DECADE}U",
        "",
        *table("l3trLog16Hi", his),
        "",
        *table("l3trLog16Lo", los),
        "",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    expected = render()
    if argv[1:] == ["--check"]:
        current = HEADER.read_bytes().replace(b"\r\n", b"\n").decode() if HEADER.exists() else ""
        if current != expected:
            print(f"{HEADER.name} is stale: run python firmware/gen_log16_table.py")
            return 1
        return 0
    if argv[1:]:
        print(__doc__)
        return 2
    HEADER.write_bytes(expected.encode())
    print(f"wrote {HEADER.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
