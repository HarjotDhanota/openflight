#!/usr/bin/env python3
"""Write (or --check) firmware/iwr6843/clock_probe_build_id.h.

clockProbe reports ``build=<fingerprint>`` so the host can tell which source
and flags produced the image it is talking to. The fingerprint is a SHA-256
over every firmware source file (line endings normalized to LF, so a Windows
checkout hashes like the Linux build) and the feature flags of that build.
One fingerprint is written per flag set the clock header can be built with;
the header picks the matching one at compile time.

Hash input, in this order: for each source path (sorted, relative to the repo,
forward slashes) the bytes ``path + NUL + content``; then
``"flags" + NUL + ",".join(sorted enabled flags)``.

    python firmware/build_fingerprint.py           # rewrite the header
    python firmware/build_fingerprint.py --check   # exit 1 if it is stale
"""

from __future__ import annotations

import hashlib
import itertools
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
APP = REPO / "firmware" / "iwr6843"
HEADER = APP / "clock_probe_build_id.h"
SOURCE_SUFFIXES = {".c", ".h", ".cfg", ".cmd"}

# Always on wherever the header is included (clock_probe.h includes it).
BASE_FLAG = "L3_USB_CLOCK_PROBE"
# Flags that change the clock build. L3_CAPTURE_EVIDENCE is derived in
# l3_dump.c from CONFIGURABLE_CAPTURE + HYBRID_CADENCE_CAPTURE.
VARIANT_FLAGS = ("L3_USB_CLOCK_COMPACT", "L3_TWO_ROUND", "L3_CAPTURE_EVIDENCE")


def sources() -> list[Path]:
    """Every file that goes into the image, except the header this script writes."""
    found = [
        path
        for path in APP.iterdir()
        if path.is_file()
        and path != HEADER
        and (path.suffix in SOURCE_SUFFIXES or path.name == "makefile")
    ]
    return sorted([REPO / "firmware" / "Makefile", *found], key=_relative)


def _relative(path: Path) -> str:
    return path.relative_to(REPO).as_posix()


def fingerprint(flags: tuple[str, ...]) -> str:
    digest = hashlib.sha256()
    for path in sources():
        content = path.read_bytes().replace(b"\r\n", b"\n")
        digest.update(_relative(path).encode() + b"\0" + content)
    digest.update(b"flags\0" + ",".join(sorted(flags)).encode())
    return digest.hexdigest()


def render() -> str:
    lines = [
        "/* Generated by firmware/build_fingerprint.py; do not edit. One build id per",
        " * feature-flag set: SHA-256 of the firmware sources plus those flags.",
        " * Regenerate after any firmware source change: python firmware/build_fingerprint.py */",
    ]
    keyword = "#if"
    for enabled in itertools.product((False, True), repeat=len(VARIANT_FLAGS)):
        on = tuple(flag for flag, flag_on in zip(VARIANT_FLAGS, enabled) if flag_on)
        tests = [
            f"defined({flag})" if flag_on else f"!defined({flag})"
            for flag, flag_on in zip(VARIANT_FLAGS, enabled)
        ]
        lines.append(f"{keyword} {' && '.join(tests)}")
        lines.append(f'#define L3_USB_CLOCK_BUILD_ID "{fingerprint((BASE_FLAG, *on))}"')
        keyword = "#elif"
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    expected = render()
    if argv[1:] == ["--check"]:
        current = HEADER.read_bytes().replace(b"\r\n", b"\n").decode() if HEADER.exists() else ""
        if current != expected:
            print(f"{_relative(HEADER)} is stale: run python firmware/build_fingerprint.py")
            return 1
        return 0
    if argv[1:]:
        print(__doc__)
        return 2
    HEADER.write_bytes(expected.encode())
    print(f"wrote {_relative(HEADER)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
